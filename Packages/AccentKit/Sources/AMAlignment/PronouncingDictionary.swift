// The bundled CMUdict and the stress-shift pairs generated from it (spec 06).

import Foundation
import AMCore

/// The CMU Pronouncing Dictionary, read from the bundled `cmudict.dict` (pinned in `CMUdict/manifest.json`).
public struct PronouncingDictionary: Sendable {
    /// Lowercase word → its variants' ARPAbet strings, in CMUdict order. Parsed into `Pronunciation` on lookup.
    private let entries: [String: [String]]

    /// Parses CMUdict text: `word PH ON ES`, variants as `word(2)`, `#` comments.
    public init(contents: String) {
        var entries: [String: [String]] = [:]
        entries.reserveCapacity(130_000)
        for rawLine in contents.split(separator: "\n", omittingEmptySubsequences: true) {
            let line = rawLine.split(separator: "#", maxSplits: 1, omittingEmptySubsequences: false).first ?? ""
            guard let space = line.firstIndex(of: " ") else { continue }
            var word = line[..<space]
            if word.last == ")", let open = word.lastIndex(of: "(") { word = word[..<open] }
            let phones = line[line.index(after: space)...].trimmingCharacters(in: .whitespaces)
            guard !word.isEmpty, !phones.isEmpty else { continue }
            entries[word.lowercased(), default: []].append(phones)
        }
        self.entries = entries
    }

    /// The bundled dictionary, read once.
    public static func bundled() throws(ResourceError) -> PronouncingDictionary { try cache.get() }

    private static let cache = Result<PronouncingDictionary, ResourceError> { () throws(ResourceError) in
        PronouncingDictionary(contents: try BundledResource.text("CMUdict/cmudict.dict"))
    }

    /// Every variant of a word (folded), in CMUdict order; empty when it's out of vocabulary.
    public func pronunciations(of word: String) -> [Pronunciation] {
        (entries[WordText.fold(word)] ?? []).compactMap { try? Pronunciation(arpabet: $0) }
    }

    public func contains(_ word: String) -> Bool { entries[WordText.fold(word)] != nil }

    /// True when the word's variants carry more than one stress pattern (the full 1 / 2 / 0 sequence), e.g. "record"
    /// (REcord / reCORD) or the weak and strong forms of "can" (K AH0 N / K AE1 N).
    public func hasStressVariants(_ word: String) -> Bool {
        Set(pronunciations(of: word).map(\.stressPattern)).count > 1
    }
}

/// `stress-shift-pairs.json`: the CMUdict words whose variants differ in primary stress, with the hand-curated
/// variant for each part of speech (null: the word stays `expectedAmbiguous` for it). Generated by
/// `tools/gen_stress_shift_pairs.py`.
public struct StressShiftPairs: Sendable {
    public struct Entry: Sendable, Hashable, Decodable {
        public struct Variant: Sendable, Hashable, Decodable {
            public let arpabet: String
            public let primary: Int?
        }

        public let variants: [Variant]
        public let noun: Int?
        public let verb: Int?
        public let adjective: Int?

        /// The variant for a part of speech, or nil when there is none (ambiguous).
        public func pronunciation(for lexicalClass: LexicalClass) -> Pronunciation? {
            let index: Int? =
                switch lexicalClass {
                case .noun: noun
                case .verb: verb
                case .adjective: adjective
                case .other: nil
                }
            guard let index, variants.indices.contains(index) else { return nil }
            return try? Pronunciation(arpabet: variants[index].arpabet)
        }
    }

    private struct Document: Decodable {
        let words: [String: Entry]
    }

    public let words: [String: Entry]

    public init(json: Data) throws(ResourceError) {
        do {
            words = try JSONDecoder().decode(Document.self, from: json).words
        } catch {
            throw .malformed("stress-shift-pairs.json")
        }
    }

    public static func bundled() throws(ResourceError) -> StressShiftPairs { try cache.get() }

    private static let cache = Result<StressShiftPairs, ResourceError> { () throws(ResourceError) in
        try StressShiftPairs(json: BundledResource.data("stress-shift-pairs.json"))
    }

    /// The entry for a word (folded) whose variants differ in primary stress; nil when it has one primary pattern.
    public func entry(for word: String) -> Entry? { words[WordText.fold(word)] }
}
